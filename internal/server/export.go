// GenerateStandaloneHTML creates a self-contained portable HTML snapshot.
func GenerateStandaloneHTML(msg *model.Message) string {
	toList := make([]string, len(msg.To))
	for i, t := range msg.To {
		if t.Name != "" {
			toList[i] = fmt.Sprintf("%s &lt;%s&gt;", t.Name, t.Address)
		} else {
			toList[i] = t.Address
		}
	}

	fromStr := msg.From.Address
	if msg.From.Name != "" {
		fromStr = fmt.Sprintf("%s &lt;%s&gt;", msg.From.Name, msg.From.Address)
	}

	otpBlock := ""
	if msg.OTP != nil && msg.OTP.Code != "" {
		otpBlock = fmt.Sprintf(`
		<div style="background: #eef2ff; border: 1px solid #c7d2fe; border-radius: 8px; padding: 12px 16px; margin: 16px 0; display: flex; align-items: center; justify-content: space-between;">
			<div>
				<div style="font-size: 11px; font-weight: 700; text-transform: uppercase; color: #4338ca; letter-spacing: 0.5px;">Verification Passcode</div>
				<div style="font-size: 12px; color: #4b5563;">%s</div>
			</div>
			<div style="font-family: ui-monospace, monospace; font-size: 24px; font-weight: 800; letter-spacing: 4px; color: #3730a3;">%s</div>
		</div>`, msg.OTP.Context, msg.OTP.Code)
	}

	return fmt.Sprintf(`<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>MailPulse Snapshot: %s</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; background: #f8fafc; margin: 0; padding: 24px; color: #1e293b; }
    .container { max-width: 800px; margin: 0 auto; background: #ffffff; border-radius: 12px; border: 1px solid #e2e8f0; overflow: hidden; box-shadow: 0 4px 6px -1px rgba(0,0,0,0.05); }
    .header-card { padding: 24px; border-bottom: 1px solid #e2e8f0; background: #fafafa; }
    .subject { font-size: 20px; font-weight: 700; margin: 0 0 12px; color: #0f172a; }
    .meta-row { font-size: 13px; color: #64748b; margin-bottom: 6px; }
    .meta-label { font-weight: 600; color: #334155; }
    .badge-score { display: inline-block; font-size: 11px; font-weight: 700; padding: 3px 8px; border-radius: 9999px; background: #ecfdf5; color: #047857; border: 1px solid #a7f3d0; margin-left: 8px; }
    .email-body { padding: 32px; background: #ffffff; }
    .footer { padding: 16px 24px; border-top: 1px solid #f1f5f9; font-size: 12px; color: #94a3b8; text-align: center; }
  </style>
</head>
<body>
  <div class="container">
    <div class="header-card">
      <div class="subject">
        %s
        <span class="badge-score">Deliverability: %d/100</span>
      </div>
      <div class="meta-row"><span class="meta-label">From:</span> %s</div>
      <div class="meta-row"><span class="meta-label">To:</span> %s</div>
      <div class="meta-row"><span class="meta-label">Date:</span> %s</div>
      %s
    </div>
    <div class="email-body">
      %s
    </div>
    <div class="footer">
      Generated by <strong>MailPulse</strong> Local SMTP Studio &bull; %s
    </div>
  </div>
</body>
</html>`,
		msg.Subject,
		msg.Subject,
		msg.SpamReport.Score,
		fromStr,
		strings.Join(toList, ", "),
		msg.ReceivedAt.Format(time.RFC1123Z),
		otpBlock,
		msg.HTMLBody,
		time.Now().Format("2006-01-02 15:04:05 UTC"),
	)
}

// StreamZIPExport exports all captured emails and attachments as a ZIP file.
func StreamZIPExport(w http.ResponseWriter, store storage.Storage) error {
	ctx := context.Background()
	summaries, _, err := store.List(ctx, "", "", 1000, 0)
	if err != nil {
		return err
	}

	w.Header().Set("Content-Type", "application/zip")
	w.Header().Set("Content-Disposition", fmt.Sprintf("attachment; filename=\"mailpulse-export-%s.zip\"", time.Now().Format("20060102-150405")))

	zw := zip.NewWriter(w)
	defer zw.Close()

	var manifest []map[string]interface{}

	for idx, s := range summaries {
		msg, err := store.Get(ctx, s.ID)
		if err != nil {
			continue
		}

		manifest = append(manifest, map[string]interface{}{
			"id":          msg.ID,
			"receivedAt":  msg.ReceivedAt,
			"from":        msg.From,
			"to":          msg.To,
			"subject":     msg.Subject,
			"spamScore":   msg.SpamReport.Score,
			"spamVerdict": msg.SpamReport.Verdict,
			"hasOtp":      msg.OTP != nil,
			"attachments": len(msg.Attachments),
		})

		// Write EML file
		cleanSubj := strings.Map(func(r rune) rune {
			if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') || r == '-' || r == '_' {
				return r
			}
			return '_'
		}, msg.Subject)
		if len(cleanSubj) > 30 {
			cleanSubj = cleanSubj[:30]
		}

		emlPath := fmt.Sprintf("messages/%03d_%s_%s.eml", idx+1, cleanSubj, msg.ID[:8])
		f, err := zw.Create(emlPath)
		if err == nil {
			_, _ = f.Write(msg.RawEML)
		}

		// Write attachments if any
		for _, att := range msg.Attachments {
			attPath := fmt.Sprintf("attachments/%s/%s", msg.ID[:8], att.Filename)
			af, err := zw.Create(attPath)
			if err == nil {
				_, _ = af.Write(att.Data)
			}
		}
	}

	// Write manifest.json
	mf, err := zw.Create("manifest.json")
	if err == nil {
		enc := json.NewEncoder(mf)
		enc.SetIndent("", "  ")
		_ = enc.Encode(map[string]interface{}{
			"exportedAt":    time.Now().Format(time.RFC3339),
			"totalMessages": len(manifest),
			"messages":      manifest,
		})
	}

	return nil
}
